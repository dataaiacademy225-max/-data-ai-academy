/**
 * Catalogue des critères CITE : barème et textes affichés au dirigeant.
 * Les textes sont relus par un humain et vérifiés par un test (formulations interdites).
 * Ton : direct, sans jargon, prudent sur les effets (« peut », jamais « garantit »).
 */

export type CriterionDefinition = {
  code: string;
  pillar: Pillar;
  maxPoints: number;
  /** Nom court, compréhensible sans connaissance technique. */
  label: string;
  /** Ce que le critère vérifie, formulé comme une question. */
  question: string;
  /** Priorité si le critère échoue ou n'est que partiellement rempli. */
  priority: Priority;
  effort: Effort;
  /** Pourquoi c'est important (impact potentiel). */
  impact: string;
  /** Ce qu'il faut faire, concrètement. */
  recommendation: string;
  /** Phrase affichée quand le critère est rempli. */
  strength: string;
};

